        <div>
            <h3 style="font-size: 1.2rem; font-weight: 700; margin-bottom: 0.5rem; color: var(--text-main);">1. Princípio Fundamental de Imputação de Vínculos</h3>
            <p>Um dos maiores problemas no jornalismo de dados e no debate público é a confusão entre <strong>gastos institucionais do Estado</strong> e <strong>gastos pessoais de governantes</strong>. No Observatório da Presidência vigora a regra inegociável: despesas de custeio predial, frotas gerais, segurança institucional e manutenção da Presidência da República nunca são atribuídas à pessoa física do governante ou da primeira-dama, salvo se houver elemento documental primário irrefutável comprovando o uso individual direto.</p>
        </div>

        <div>
            <h3 style="font-size: 1.2rem; font-weight: 700; margin-bottom: 0.5rem; color: var(--text-main);">2. Taxonomia Rigorosa de Vínculos</h3>
            <ul style="margin-left: 1.5rem; display: flex; flex-direction: column; gap: 0.5rem;">
                <li><strong>DIRETA:</strong> Despesa comprovadamente individual da autoridade (ex.: cartão emitido em seu nome com lançamento próprio).</li>
                <li><strong>AGENDA_OFICIAL:</strong> Despesas associadas a eventos ou compromissos públicos específicos registrados na agenda oficial.</li>
                <li><strong>COMITIVA_VIAGEM:</strong> Transporte, hospedagem e segurança de comitivas e delegações em missões governamentais.</li>
                <li><strong>INSTITUCIONAL:</strong> Despesas operacionais e administrativas gerais do órgão (Casa Civil, Secretaria de Administração, GSI).</li>
                <li><strong>NAO_IDENTIFICADO:</strong> Lançamentos cujo nível de detalhamento da fonte governamental não permite atestar o beneficiário ou vínculo.</li>
            </ul>
        </div>

        <div>
            <h3 style="font-size: 1.2rem; font-weight: 700; margin-bottom: 0.5rem; color: var(--text-main);">3. Não Duplicidade de Fases Contábeis</h3>
            <p>No orçamento público federal, uma mesma despesa passa pelas fases de <em>Empenho</em>, <em>Liquidação</em> e <em>Pagamento</em>. Este portal nunca soma as três fases como despesas diferentes, o que geraria tripla contagem artificial de gastos públicos. A base de cálculo principal é o valor efetivamente liquidado/pago.</p>
        </div>

        <div>
            <h3 style="font-size: 1.2rem; font-weight: 700; margin-bottom: 0.5rem; color: var(--text-main);">4. Metodologia de Correção pela Inflação (IPCA)</h3>
            <p>Para viabilizar comparações históricas reais entre 2003 e a atualidade, o sistema utiliza a <strong>Série 433 do IPCA</strong> obtida via API oficial do Banco Central do Brasil. O fator acumulado de correção monetária é aplicado sobre o valor nominal com referência fixada em <strong>Setembro de 2026</strong>, permitindo visualizar o valor real contemporâneo.</p>
        </div>

        <div>
            <h3 style="font-size: 1.2rem; font-weight: 700; margin-bottom: 0.5rem; color: var(--text-main);">5. Finalidade dos Alertas do Radar Investigativo</h3>
            <p>Alertas estatísticos são instrumentos automatizados de triagem e apontamento de dados atípicos (outliers, concentração diária, alta recorrência de fornecedores). Eles <strong>não constituem juízo de culpa, ilicitude ou corrupção</strong>, sendo estritamente ferramentas analíticas para pesquisa e auditoria cidadã.</p>
        </div>
