        <h3 style="font-size: 1.15rem; font-weight: 700;">1. Natureza Pública dos Dados Exibidos</h3>
        <p>Os dados constantes desta plataforma decorrem do cumprimento do dever de transparência ativa do Estado brasileiro, previsto no art. 37 da Constituição Federal e na Lei nº 12.527/2011 (LAI). As informações relativas a autoridades públicas no exercício de suas funções estatais e a agentes remunerados pelo erário possuem publicidade constitucional estrita, prevalecendo o interesse público sobre o sigilo individual.</p>

        <h3 style="font-size: 1.15rem; font-weight: 700;">2. Dados dos Visitantes e Usuários do Portal</h3>
        <p>O portal não comercializa, não cede e não compartilha dados de navegação com terceiros. Não coletamos dados pessoais identificáveis dos visitantes públicos comuns. Coletamos apenas logs técnicos de requisição (endereço IP, user-agent e horário) estritamente necessários para segurança da infraestrutura contra ataques de negação de serviço (DDoS) e limitação de taxa (Rate Limiting).</p>

        <h3 style="font-size: 1.15rem; font-weight: 700;">3. Cookies e Armazenamento Local</h3>
        <p>Utilizamos cookies apenas para gerenciamento de sessão autenticada na área restrita administrativa (com atributos HttpOnly, SameSite=Lax e Secure quando sob HTTPS). Para preferências de interface no portal público (como o tema claro/escuro), utilizamos exclusivamente o <code>localStorage</code> do próprio navegador do usuário.</p>
